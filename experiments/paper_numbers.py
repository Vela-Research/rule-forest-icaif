"""Collect every number the paper quotes into results/PAPER_NUMBERS.md, with its source file.

  python experiments/paper_numbers.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"


def load(name):
    return json.loads((R / f"{name}.json").read_text())


def f(x, d=3):
    return f"{x:.{d}f}"


def sd(row, k):
    return f"{row[k]:.3f} ± {row[k + '_sd']:.3f}" if k + "_sd" in row else f(row[k])


def ci(b):
    return f"{b['delta']:+.3f} [{b['ci95'][0]:+.3f}, {b['ci95'][1]:+.3f}], p = {b['p']:.2f}"


NAME = {"vote_hamming_0.15": "Rule Forest", "vote_expert": "Expert arm", "en_gpt_4o_mini": "Elastic net",
        "en_expert": "Elastic net (58 questions)", "o3_few_shot": "o3 few-shot",
        "gpt_4o_mini_minus_gpt_5_2": "GPT-4o-mini minus GPT-5.2 (votes)",
        "gpt_4o_mini_minus_claude_sonnet_4_5": "GPT-4o-mini minus Claude Sonnet 4.5 (votes)",
        "gpt_4o_mini": "GPT-4o-mini", "claude_sonnet_4_5": "Claude Sonnet 4.5", "gpt_5_2": "GPT-5.2"}


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    return out + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]


def main():
    t2, t3, ex, sl = load("table2"), load("table3"), load("expert"), load("shortlists")
    q, f4, f5 = load("questions"), load("figure4"), load("figure5")
    rows, d, iv = t2["rows"], t2["rule_forest_detail"], t2["intervals"]
    L = ["# Numbers in the paper", "",
         "Generated by `experiments/paper_numbers.py` from the files in `results/`. Every value is "
         "rounded to 3 decimals. Intervals are paired founder bootstraps (10,000 resamples, seed 42), "
         "shown as difference [95% interval] and two-sided p.", ""]

    L += ["## Table 2", "", "Source: `results/table2.json` (`rows`).", ""]
    names = [("rule_forest", "Rule Forest", "LLM questions + equal-weight vote"),
             ("elastic_net", "Elastic net", "Same questions, learned weights"),
             ("engineered_ml", "Engineered ML", "Engineered features + elastic net"),
             ("embeddings", "Embeddings", "Embeddings + XGBoost"),
             ("o3_few_shot", "o3", "Few-shot prompting"),
             ("gpt_4o_mini_zero_shot", "GPT-4o-mini", "Zero-shot prompting"),
             ("rrm", "RRM", "LLM rule mining"),
             ("gptree", "GPTree", "LLM decision tree")]
    L += table(["Row", "Approach", "Precision", "Recall", "F0.5"],
               [(n, a, sd(rows[k], "precision"), sd(rows[k], "recall"), sd(rows[k], "f05"))
                for k, n, a in names if k in rows])
    b = iv["rule_forest_minus_elastic_net"]
    L += ["", "Rule Forest minus elastic net (`intervals.rule_forest_minus_elastic_net`):",
          f"- F0.5 {ci(b['f05'])}", f"- precision {ci(b['precision'])}", f"- recall {ci(b['recall'])}",
          f"- Rule Forest minus o3 few-shot, F0.5 {ci(iv['rule_forest_minus_o3_few_shot']['f05'])}",
          f"- Elastic net minus o3 few-shot, F0.5 {ci(iv['elastic_net_minus_o3_few_shot']['f05'])}", ""]

    L += ["## Section 5.1, the shortlist", "", "Source: `results/table2.json` (`rule_forest_detail`).", "",
          f"- Evaluation founders {d['founders']:,}, successes {d['successes']}, base rate {100 * d['base_rate']:.2f}% "
          f"(1 in {1 / d['base_rate']:.0f}).",
          f"- Rule Forest flags {d['flagged_per_repeat_mean']:.0f} founders per repeat, of whom "
          f"{d['hits_per_repeat_mean']:.1f} succeed, so precision is {f(rows['rule_forest']['precision'])}, or 1 in "
          f"{1 / rows['rule_forest']['precision']:.1f}.",
          f"- Screening at random, a partner would review {d['profiles_screened_at_random_for_the_same_hits']:.0f} "
          f"profiles to find as many successes.",
          f"- The elastic net flags {d['elastic_net_flagged_per_repeat_mean']:.0f} founders per repeat and keeps a "
          f"median of {d['elastic_net_nonzero_weights_median']:.0f} non-zero weights; the vote keeps "
          f"{d['N_median']:.0f} equally weighted questions.",
          f"- With the {q['blank_answers']['gpt_4o_mini']['reasked']} re-asked blank answers, Rule Forest's F0.5 is {f(d['with_reasked_blanks']['f05'], 4)} "
          f"({f(rows['rule_forest']['f05'], 4)} without them).", ""]

    e, rf = ex["expert_arm"], ex["rule_forest"]
    xi = ex["intervals"]
    L += ["## Section 5.2, expert questions", "", "Source: `results/expert.json`.", "",
          f"- Rule Forest P {sd(rf, 'precision')}, R {sd(rf, 'recall')}, F0.5 {sd(rf, 'f05')}.",
          f"- With the 8 expert questions P {sd(e, 'precision')}, R {sd(e, 'recall')}, F0.5 {sd(e, 'f05')} "
          f"(precision 1 in {1 / e['precision']:.1f}; median {e['N_median']:.0f} questions; pool "
          f"{e['pool_size_range'][0]} to {e['pool_size_range'][1]}).",
          f"- Expert arm minus Rule Forest: precision {ci(xi['expert_minus_rule_forest']['precision'])}; "
          f"F0.5 {ci(xi['expert_minus_rule_forest']['f05'])}.",
          f"- Elastic net on the same 58 questions: P {sd(ex['elastic_net_58_questions'], 'precision')}, "
          f"R {sd(ex['elastic_net_58_questions'], 'recall')}, F0.5 {sd(ex['elastic_net_58_questions'], 'f05')}.",
          f"- Expert arm minus that elastic net: F0.5 {ci(xi['expert_minus_elastic_net_58']['f05'])}; "
          f"precision {ci(xi['expert_minus_elastic_net_58']['precision'])}.",
          f"- Elastic net, 58 minus 50 questions: recall {ci(xi['elastic_net_58_minus_elastic_net_50']['recall'])}; "
          f"precision {ci(xi['elastic_net_58_minus_elastic_net_50']['precision'])}.", ""]

    L += ["## Precision at equal shortlist sizes (Section 5.2)", "",
          f"Source: `results/shortlists.json`. o3 flags {sl['o3_flagged']} founders and gives no order "
          "inside them, so its shortlist below that size is a random subset.", ""]
    arms = ["vote_hamming_0.15", "vote_expert", "en_gpt_4o_mini", "en_expert", "o3_few_shot"]
    L += table(["Founders on the list", "Rule Forest", "Expert arm", "Elastic net", "Elastic net, 58 q.", "o3"],
               [(r["K"], *(f(r[a]["precision"]) for a in arms)) for r in sl["table"]])
    L += [""] + [f"- {r['K']} founders. {NAME[r['a']]} minus {NAME[r['b']]}, precision {r['precision_a']:.3f} vs "
                 f"{r['precision_b']:.3f}, {ci(r)}" for r in sl["intervals"]]
    L += ["- These 15 comparisons are not corrected for multiplicity.", ""]

    cell = t3["vote"]
    lab = {"vote_hamming_0.15": "Hamming 0.15 (default)", "vote_jaccard_0.90": "Jaccard 0.90",
           "vote_cosine_0.85": "Cosine clustering 0.85", "vote_hamming_0.10": "Hamming 0.10",
           "vote_hamming_0.20": "Hamming 0.20", "vote_claude_sonnet_4_5": "Claude Sonnet 4.5 (vote)",
           "vote_gpt_5_2": "GPT-5.2 (vote)"}
    L += ["## Table 3 and Section 5.3", "", "Source: `results/table3.json`.", ""]
    L += table(["Setting", "F0.5", "Pool size", "Median N"],
               [(lab[k], sd(cell[k], "f05"), f"{cell[k]['pool_size_range'][0]} to {cell[k]['pool_size_range'][1]}",
                 f"{cell[k]['N_median']:.0f}") for k in lab])
    en = t3["elastic_net"]
    L += ["", f"Elastic net: GPT-4o-mini {sd(en['en_gpt_4o_mini'], 'f05')}, Claude Sonnet 4.5 "
              f"{sd(en['en_claude_sonnet_4_5'], 'f05')}, GPT-5.2 {sd(en['en_gpt_5_2'], 'f05')}.", ""]
    L += [f"- {NAME[k]}, F0.5 {ci(v)} (n = {v['n']:,})" for k, v in t3["generator_intervals"].items()]
    L += [f"- {NAME[k]} vote minus elastic net, F0.5 {ci(v)}" for k, v in t3["vote_minus_elastic_net"].items()]
    L += ["", f"- Across the 100 outer folds the vote selects a median of {d['N_median']:.0f} questions with threshold "
              f"{d['T_median']:.0f}; T/N median {d['T_over_N_median']:.2f}, interquartile range "
              f"{d['T_over_N_iqr'][0]:.2f} to {d['T_over_N_iqr'][1]:.2f}; N equals the whole pool in "
              f"{d['folds_with_N_equal_to_pool_size']} folds; the in-fold pool holds "
              f"{d['pool_size_range'][0]} to {d['pool_size_range'][1]} questions.",
          "- The questions selected most often, with the number of the 100 folds that select them, are "
          + "; ".join(f"{x['question']} ({x['folds']})" for x in d["questions_selected_most_often"][:8]) + ".", ""]

    g, c, bl, fo = q["generation"], q["question_chain"], q["blank_answers"]["gpt_4o_mini"], q["founders"]
    L += ["## Sections 4.1 and 4.2, questions and missing answers", "", "Source: `results/questions.json`.", "",
          f"- Generation used {g['prompts']} prompts of up to 20 founders; {g['distinct_successes_shown']} of "
          f"{g['successes']} successful generation founders shown, "
          + ("each once" if g['most_times_one_success_is_shown'] == 1 else "some more than once") + "; labels never shown.",
          f"- Questions went from {c['generated']} written to {c['exact_unique']} exact-unique, {c['after_semantic_dedup']} after "
          f"semantic de-duplication and {c['scored_on_evaluation_founders']} scored on the evaluation founders "
          f"({c['after_semantic_dedup'] - c['scored_on_evaluation_founders']} not carried forward).",
          f"- Blank answers are {bl['blank']} of {bl['cells']:,} cells ({100 * bl['blank_share']:.2f}%); "
          f"{bl['reasked']} re-asked, {bl['reasked_yes']} came back YES.",
          f"- There are {fo['evaluation_profiles']:,} evaluation profiles and {fo['founders_in_gpt_4o_mini_matrix']:,} "
          "founders in the answer matrix.", ""]

    L += ["## Figure 4", "", "Source: `results/figure4.json`. Gap = vote minus elastic net, held-out F0.5, mean over "
          "draws; in brackets, the draws in which the vote leads.", ""]
    names4 = {"S4": "1.93% base rate", "S1": "5% base rate", "S5": "9% base rate", "S2": "n = 3,160",
              "S3": "158 successes (by base rate)"}
    for s, name in names4.items():
        tab = f4["slices"][s]["table"]
        xs = (lambda r: f"{100 * r['base_rate']:.2f}%") if s == "S3" else (lambda r: str(r["successes"]))
        L.append(f"- {name}: " + ", ".join(f"{xs(r)} {r['gap']:+.3f} ({r['vote_leads_in_draws']}/{r['draws']})"
                                          for r in tab) + f"; Spearman {f4['slices'][s]['spearman_gap']:+.2f}")
    s2 = f4["slices"]["S2"]["table"]
    L += ["- Panel (a) vote / elastic net at 1.93%: " + ", ".join(
              f"{r['successes']}: {r['vote_f05']:.3f} / {r['en_f05']:.3f}" for r in f4["slices"]["S4"]["table"]),
          "- Panel (e), n = 3,160: share of questions two folds have in common, vote / elastic net: " + ", ".join(
              f"{r['successes']}: {r['vote_selection_jaccard']:.2f} / {r['en_support_jaccard']:.2f}" for r in s2),
          f"- The elastic net's training-minus-held-out F0.5 is the larger at "
          f"{f4['elastic_net_overfits_more_at_points']} of {f4['points']} points.", ""]

    L += ["## Figure 5", "", f"Source: `results/figure5.json`. {f5['loans']:,} loans after removing the 40 "
          "generation loans.", ""]
    L += table(["Positives", "Base rate", "Vote", "Elastic net", "Gap", "Vote leads"],
               [(r["successes"], f"{100 * r['base_rate']:.1f}%", f(r["vote_f05"]), f(r["en_f05"]), f"{r['gap']:+.3f}",
                 f"{r['vote_leads_in_draws']}/{r['draws']}") for r in f5["table"]])
    if (R / "figure5_as_scored.json").exists():
        raw = {r["successes"]: r for r in load("figure5_as_scored")["table"]}
        L += ["", "Without the re-alignment of short Kiva replies (`results/figure5_as_scored.json`), for comparison:", ""]
        L += table(["Positives", "Vote", "Elastic net", "Gap", "Vote leads"],
                   [(c, f(r["vote_f05"]), f(r["en_f05"]), f"{r['gap']:+.3f}", f"{r['vote_leads_in_draws']}/{r['draws']}")
                    for c, r in sorted(raw.items())])
    L += [""]
    (R / "PAPER_NUMBERS.md").write_text("\n".join(L))
    print(f"wrote {R / 'PAPER_NUMBERS.md'}")


if __name__ == "__main__":
    main()
